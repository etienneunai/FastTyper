import fs from "node:fs";
import zlib from "node:zlib";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const wordlistPath = path.join(__dirname, "src/wordlist.json");
const outputPath = path.join(__dirname, "src/wordlist-compressed.ts");

if (!fs.existsSync(wordlistPath)) {
    console.error(`Error: ${wordlistPath} not found`);
    process.exit(1);
}

const raw = fs.readFileSync(wordlistPath);
const gzipped = zlib.gzipSync(raw);
const base64 = gzipped.toString("base64");

const tsContent = `// Auto-generated by generate-wordlist.mjs - do not edit directly
export const GZIPPED_WORDLIST_B64 = "${base64}";
`;

fs.writeFileSync(outputPath, tsContent, "utf8");
console.log(`Generated ${outputPath} (${gzipped.length} gzipped bytes)`);
